import { useState } from "react";

/* =========================================================
 * SCADA GLOBAL TYPE
 * ========================================================= */

declare global {
  interface Window {
    SCADA?: {
      writeTag?: (tag: string, value: boolean) => void;
    };
  }
}

/* =========================================================
 * TOGGLE BUTTON PROPS
 * ========================================================= */

export interface ToggleButtonProps {
  /* -------------------------------------------------------
   * POSITION
   * ------------------------------------------------------- */

  x?: number;
  y?: number;

  /* -------------------------------------------------------
   * SIZE
   * ------------------------------------------------------- */

  width?: number;
  height?: number;

  /* -------------------------------------------------------
   * SCADA TAG
   * ------------------------------------------------------- */

  tag?: string;

  /* -------------------------------------------------------
   * LABEL
   * ------------------------------------------------------- */

  label?: string;

  onLabel?: string;
  offLabel?: string;

  /* -------------------------------------------------------
   * COLORS
   * ------------------------------------------------------- */

  backgroundColor?: string;
  onColor?: string;

  borderColor?: string;
  labelColor?: string;

  /* -------------------------------------------------------
   * TYPOGRAPHY
   * ------------------------------------------------------- */

  fontSize?: number;
  fontFamily?: string;
  fontWeight?: string | number;

  /* -------------------------------------------------------
   * STATE
   * ------------------------------------------------------- */

  value?: boolean;

  /* -------------------------------------------------------
   * CALLBACK
   * ------------------------------------------------------- */

  onChange?: (state: boolean) => void;
  onClick?: (state: boolean) => void;
}

/* =========================================================
 * TOGGLE BUTTON
 * ========================================================= */

function ToggleButton({
  /* -------------------------------------------------------
   * POSITION
   * ------------------------------------------------------- */

  x = 0,
  y = 0,

  /* -------------------------------------------------------
   * SIZE
   * ------------------------------------------------------- */

  width = 120,
  height = 50,

  /* -------------------------------------------------------
   * SCADA TAG
   * ------------------------------------------------------- */

  tag = "",

  /* -------------------------------------------------------
   * LABEL
   * ------------------------------------------------------- */

  label = "TOGGLE",

  onLabel = "ON",
  offLabel = "OFF",

  /* -------------------------------------------------------
   * COLORS
   * ------------------------------------------------------- */

  backgroundColor = "#334155",
  onColor = "#22c55e",

  borderColor = "#38bdf8",
  labelColor = "#ffffff",

  /* -------------------------------------------------------
   * TYPOGRAPHY
   * ------------------------------------------------------- */

  fontSize = 18,
  fontFamily = "Segoe UI",
  fontWeight = "bold",

  /* -------------------------------------------------------
   * STATE
   * ------------------------------------------------------- */

  value,

  /* -------------------------------------------------------
   * CALLBACK
   * ------------------------------------------------------- */

  onChange,
  onClick,
}: ToggleButtonProps) {
  /* =======================================================
   * INTERNAL STATE
   * ======================================================= */

  const [internalState, setInternalState] = useState(false);

  /* =======================================================
   * TOGGLE STATE
   * ======================================================= */

  const state = value !== undefined ? value : internalState;

  /* =======================================================
   * TOGGLE HANDLER
   * ======================================================= */

  const handleToggle = () => {
    /* -----------------------------------------------------
     * NEXT STATE
     * ----------------------------------------------------- */

    const nextState = !state;

    /* -----------------------------------------------------
     * INTERNAL STATE
     *
     * Hanya digunakan jika uncontrolled.
     * ----------------------------------------------------- */

    if (value === undefined) {
      setInternalState(nextState);
    }

    /* -----------------------------------------------------
     * SCADA WRITE
     * ----------------------------------------------------- */

    if (tag && window.SCADA?.writeTag) {
      window.SCADA.writeTag(tag, nextState);
    }

    /* -----------------------------------------------------
     * REACT CALLBACK
     * ----------------------------------------------------- */

    onChange?.(nextState);

    onClick?.(nextState);
  };

  /* =======================================================
   * CURRENT LABEL
   * ======================================================= */

  const currentLabel = state ? onLabel : offLabel;

  /* =======================================================
   * CURRENT COLOR
   * ======================================================= */

  const currentColor = state ? onColor : backgroundColor;

  /* =======================================================
   * RENDER
   * ======================================================= */

  return (
    <g
      transform={`translate(${x}, ${y})`}
      style={{
        cursor: "pointer",
      }}
      pointerEvents="all"
      onClick={handleToggle}
      role="button"
      aria-label={label}
      aria-pressed={state}
    >
      {/* =================================================
       * TOOLTIP / ACCESSIBILITY
       * ================================================= */}

      <title>
        {label}: {currentLabel}
      </title>

      {/* =================================================
       * BUTTON
       * ================================================= */}

      <rect
        x={0}
        y={0}
        width={width}
        height={height}
        rx={8}
        fill={currentColor}
        stroke={borderColor}
        strokeWidth={2}
        pointerEvents="none"
      />

      {/* =================================================
       * LABEL
       * ================================================= */}

      <text
        x={width / 2}
        y={height / 2}
        textAnchor="middle"
        dominantBaseline="middle"
        fill={labelColor}
        fontSize={fontSize}
        fontFamily={fontFamily}
        fontWeight={fontWeight}
        pointerEvents="none"
      >
        {currentLabel}
      </text>
    </g>
  );
}

export default ToggleButton;
